/** 英超球队数组 */
var teams = [MCI_2023, LIV_2005, ARS_2017, CHE_2012, MUN_1999];

/** 国家队数组 */
var nationalTeams = [BRA_2002, FRA_2018, GER_2014];

/**
 * 随机抽取一支球队
 * @param {string} mode - 游戏模式: 'league' 英超联赛 / 'cup' 国家队杯赛
 * @returns {Object} 随机球队数据对象
 */
function getRandomTeam(mode) {
  var pool = (mode === 'cup') ? nationalTeams : teams;
  var index = Math.floor(Math.random() * pool.length);
  return pool[index];
}

/**
 * 获取指定模式下的全部球队（用于生成对手）
 * @param {string} mode - 游戏模式
 * @returns {Array} 球队数组
 */
function getAllTeams(mode) {
  return (mode === 'cup') ? nationalTeams : teams;
}

/**
 * 获取指定模式下除指定球队外的全部球队（用于生成对手）
 * 深拷贝球队数据，防止与选秀池共享引用导致数据污染
 * @param {string} mode - 游戏模式
 * @param {string} excludeTeamId - 排除的球队ID
 * @returns {Array} 对手球队数组（深拷贝）
 */
function getOpponentTeams(mode, excludeTeamId) {
  var all = getAllTeams(mode);
  return all.filter(function(t) { return t.id !== excludeTeamId; }).map(function(t) {
    // 深拷贝球队对象，避免修改原始data.js数据
    return {
      id: t.id, name: t.name, shortName: t.shortName, season: t.season,
      players: t.players.map(function(p) {
        // 浅拷贝每个球员对象（球员属性为基本类型，浅拷贝足够）
        var copy = {};
        for (var k in p) {
          if (p.hasOwnProperty(k)) copy[k] = p[k];
        }
        return copy;
      })
    };
  });
}
