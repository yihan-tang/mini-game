// ==================== 辅助函数 ====================

/**
 * 创建球员数据对象
 * @param {string} id - 唯一ID
 * @param {string} name - 球员姓名
 * @param {string} pos - 位置(GK/CB/FB/CDM/CAM/FW)
 * @param {number} ovr - 综合总评 70-99
 * @param {number} def - 防守值
 * @param {number} atk - 进攻值
 * @param {number} int - 拦截值
 * @param {string} nat - 国籍
 * @param {string} team - 所属球队
 * @param {string} season - 赛季标识
 * @param {boolean} legend - 是否传奇
 */
function _p(id, name, pos, ovr, def, atk, int, nat, team, season, legend) {
  return {
    id: id, name: name, position: pos, overall: ovr,
    defense: def, attack: atk, intercept: int,
    nationality: nat, team: team, season: season, isLegend: legend || false
  };
}

/**
 * 创建球队数据对象
 * @param {string} id - 球队ID
 * @param {string} name - 球队名称
 * @param {string} shortName - 简称
 * @param {string} season - 赛季
 * @param {Array} players - 球员数组
 */
function _t(id, name, shortName, season, players) {
  return { id: id, name: name, shortName: shortName, season: season, players: players };
}

